"""Agent Mesh integration.

The local ``agentmesh-node`` publishes each of our agents as an ``a2a`` service
(generated ``agentmesh-node.yaml``) and proxies calls to remote agents at
``/mesh/<peer-id>/a2a/<service>/``. Discovery uses the node's
``GET /mesh/service/discover`` route.
"""

import logging
from dataclasses import dataclass
from pathlib import Path

import httpx
import yaml

from agentfleet_node.config import Settings
from agentfleet_node.models import Agent
from agentfleet_node.naming import InvalidAgentId, from_service_name, owner_of, to_service_name
from agentfleet_node.store import Store

log = logging.getLogger(__name__)


class AgentOffline(Exception):
    pass


@dataclass
class Endpoint:
    agent_id: str
    url: str  # A2A base URL (agent card lives under it)
    via_mesh: bool
    peer_id: str | None = None
    description: str = ""


def local_a2a_url(settings: Settings, agent_id: str) -> str:
    return f"{settings.public_base_url}/a2a/{to_service_name(agent_id)}/"


def render_node_config(settings: Settings, agents: list[Agent]) -> str:
    services = [
        {
            "type": "a2a",
            "name": to_service_name(a.id),
            "description": (a.description or a.name)[:500],
            "target_url": local_a2a_url(settings, a.id),
        }
        for a in agents
        if a.enabled
    ]
    doc = {"version": "v1alpha1", "labels": {"owner": settings.owner}, "services": services}
    return "# Generated by agentfleet-node; restart agentmesh-node after changes.\n" + yaml.safe_dump(doc, sort_keys=False)


def write_node_config(settings: Settings, agents: list[Agent]) -> bool:
    """Write agentmesh-node.yaml. Returns True when the content changed."""
    path: Path = settings.mesh_node_config_path
    content = render_node_config(settings, agents)
    if path.exists() and path.read_text() == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    log.info("wrote %s; restart agentmesh-node to publish the change", path)
    return True


class MeshDirectory:
    def __init__(self, settings: Settings, store: Store):
        self.settings = settings
        self.store = store
        self.config_dirty = False

    def mesh_headers(self) -> dict[str, str]:
        token = self.settings.read_mesh_token()
        return {"X-Mesh-Authentication": f"Bearer {token}"} if token else {}

    def sync_node_config(self) -> None:
        if write_node_config(self.settings, self.store.list_agents()):
            self.config_dirty = True
            self.store.bus.publish({"type": "mesh", "config_dirty": True})

    async def node_status(self) -> dict:
        try:
            async with httpx.AsyncClient(timeout=3) as c:
                r = await c.get(f"{self.settings.mesh_node_url}/healthz")
                healthy = r.status_code == 200
        except httpx.HTTPError:
            healthy = False
        return {
            "node_url": self.settings.mesh_node_url,
            "node_healthy": healthy,
            "config_path": str(self.settings.mesh_node_config_path),
            "config_dirty": self.config_dirty,
            "static_peers": self.settings.static_peers,
        }

    async def discover(self, service: str | None = None) -> list[Endpoint]:
        params: dict[str, str | int] = {"type": "a2a", "limit": 200, "timeout": "5s"}
        if service:
            params["name"] = service
        try:
            async with httpx.AsyncClient(timeout=15, headers=self.mesh_headers()) as c:
                r = await c.get(f"{self.settings.mesh_node_url}/mesh/service/discover", params=params)
                r.raise_for_status()
                rows = r.json() or []
        except (httpx.HTTPError, ValueError) as e:
            log.warning("mesh discovery failed: %s", e)
            return []
        out = []
        for row in rows:
            name = row.get("srv_name", "")
            try:
                agent_id = from_service_name(name)
            except InvalidAgentId:
                continue
            peer = row.get("peer_id")
            url = row.get("local_proxy_url") or f"{self.settings.mesh_node_url}/mesh/{peer}/a2a/{name}/"
            out.append(Endpoint(agent_id, url.rstrip("/") + "/", True, peer, row.get("srv_description", "")))
        return out

    async def list_agents(self) -> list[dict]:
        seen: dict[str, dict] = {}
        for a in self.store.list_agents():
            if a.enabled:
                seen[a.id] = {"agent_id": a.id, "name": a.name, "description": a.description, "location": "local", "online": True}
        for owner, base in self.settings.static_peers.items():
            for row in await self._static_peer_agents(owner, base):
                seen.setdefault(row["agent_id"], row)
        for ep in await self.discover():
            seen.setdefault(ep.agent_id, {"agent_id": ep.agent_id, "name": ep.agent_id, "description": ep.description, "location": "mesh", "peer_id": ep.peer_id, "online": True})
        return sorted(seen.values(), key=lambda r: r["agent_id"])

    async def _static_peer_agents(self, owner: str, base: str) -> list[dict]:
        try:
            async with httpx.AsyncClient(timeout=5) as c:
                r = await c.get(f"{base.rstrip('/')}/api/public/agents")
                r.raise_for_status()
                return [{**row, "location": "static", "online": True} for row in r.json()]
        except httpx.HTTPError:
            return []

    async def resolve(self, agent_id: str) -> Endpoint:
        local = self.store.get_agent(agent_id)
        if local and local.enabled:
            return Endpoint(agent_id, local_a2a_url(self.settings, agent_id), via_mesh=False)
        owner = owner_of(agent_id)
        if owner in self.settings.static_peers:
            base = self.settings.static_peers[owner].rstrip("/")
            return Endpoint(agent_id, f"{base}/a2a/{to_service_name(agent_id)}/", via_mesh=False)
        for ep in await self.discover(to_service_name(agent_id)):
            if ep.agent_id == agent_id:
                return ep
        raise AgentOffline(f"agent {agent_id} is offline or not visible to this node")
